@dataclass
class GapValue:
    """One decision, covering ``raw_count`` live values that reduced to it."""

    value: str | None
    table: str
    field_name: str
    decision: str
    reason: str
    raw_count: int = 1
    normalised: bool = False
    redacted: bool = False
    sources: list[str] = field(default_factory=list)
    detail: str = ""

    @property
    def is_proposal(self) -> bool:
        return self.decision == PROPOSE


@dataclass
class TableGaps:
    """Every missing value for one context table, classified."""

    table_name: str
    fields: list[str] = field(default_factory=list)
    table_id: str | None = None
    key_attr: str = "key"
    status: str = ""
    records: int = 0
    consumers: list[str] = field(default_factory=list)
    read_by_rules: bool = False
    truncated_sample: bool = False
    note: str = ""
    # Live values examined for this table (i.e. len(TableValidation.missing)).
    examined: int = 0
    propose: list[GapValue] = field(default_factory=list)
    withhold: list[GapValue] = field(default_factory=list)

    @property
    def proposed(self) -> int:
        """Distinct values proposed. Never a lower bound on its own — see note."""
        return len(self.propose)

    @property
    def withheld_values(self) -> int:
        """Live values withheld, counted BEFORE normalisation collapsed them."""
        return sum(g.raw_count for g in self.withhold)

    @property
    def withheld_distinct(self) -> int:
        """Withheld entries after normalisation — 3,573 Purview values give 2."""
        return len(self.withhold)

    @property
    def accounted(self) -> int:
        return sum(g.raw_count for g in self.propose + self.withhold)

    @property
    def balanced(self) -> bool:
        """Every examined value landed in exactly one bucket."""
        return self.accounted == self.examined

    def by_reason(self) -> dict[str, int]:
        out: dict[str, int] = {}
        for g in self.withhold:
            out[g.reason] = out.get(g.reason, 0) + g.raw_count
        return dict(sorted(out.items(), key=lambda kv: (-kv[1], kv[0])))


@dataclass
class GapReport:
    """Gap analysis across every AI/LLM context table."""

    tenant: str
    collected_at: str
    lookback_days: int = 30
    api_calls: int = 0
    truncated_fields: list[str] = field(default_factory=list)
    # Fields re-enumerated at a higher row cap because the standing sample was
    # capped. Recorded so a reader can tell a complete answer from a sampled one.
    deepened_fields: list[str] = field(default_factory=list)
    tables: list[TableGaps] = field(default_factory=list)

    @property
    def lower_bound(self) -> bool:
        """True when at least one sample was truncated — no count is complete."""
        return bool(self.truncated_fields)

    @property
    def total_proposed(self) -> int:
        return sum(t.proposed for t in self.tables)

    @property
    def balanced(self) -> bool:
        return all(t.balanced for t in self.tables)


# --- helpers -----------------------------------------------------------------


def _sources(profile: TenantProfile, fields: list[str], value: str) -> list[str]:
    """Vendor/product attributions for a value, across every field it may sit in."""
    out: set[str] = set()
    for f in fields:
        out.update(profile.sources_for(f, value))
    return sorted(out)


def _pack_for_sources(
    sources: list[str], packs: dict[str, VendorPack]
) -> VendorPack | None:
    """The pack for the product that emitted this value, if it is recognised."""
    for s in sources:
        vendor, _, product = s.partition(" / ")
        pack = match_pack(vendor.strip(), product.strip(), packs)
        if pack:
            return pack
    return None


def _normalising_pack(
    sources: list[str], packs: dict[str, VendorPack]
) -> VendorPack | None:
    """The pack whose alert_name knowledge applies to this value.

    Prefers the exact product's pack. Falls back to a SIBLING pack from the same
    vendor when the exact pack carries no normalisation knowledge — Check Point
    emits the same ``dga-*.TC.*`` tokens under both ``SmartDefense`` and
    ``Check Point NGFW``, and only the SmartDefense pack documents them. On a
    live tenant that fallback moved 132 values from "unrelated" to the truthful
    "machine-generated".

    ``match_pack`` deliberately refuses a vendor-level fallback because a wrong
    pack supplies a wrong role, taxonomy and identity field. Nothing of the sort
    happens here: the only thing borrowed is a noise/normalisation regex, and a
    regex that does not match changes nothing. The failure mode is bounded to
    withholding, never to proposing.
    """
    own = _pack_for_sources(sources, packs)
    if own and (own.alert_name_pattern or own.alert_name_noise):
        return own

    if own:
        vendors = {own.vendor.lower()}
    else:
        vendors = {s.partition(" / ")[0].strip().lower() for s in sources if s}
    for pack in packs.values():
        if pack.vendor.lower() in vendors and (
            pack.alert_name_pattern or pack.alert_name_noise
        ):
            return pack
    return own


def is_per_record(value: str) -> bool:
    """Whether a value was built per event rather than per policy.

    Such a value can never be matched by an exact-match context table, and on a
    DLP feed it carries the message subject — which is customer content.
    """
    v = (value or "").strip()
    return len(v) > _MAX_ENTRY_CHARS or bool(_PER_RECORD.search(v))


def _redact(
    *,
    value: str,
    field_name: str,
    decision: str,
    reason: str,
    normalised: bool,
    include_withheld: bool,
) -> bool:
    """Whether this value's text must be kept out of the output file."""
    if decision == PROPOSE:
        # Proposals are per-record-rejected before they get here.
        return False
    if reason == REASON_HIGH_CARDINALITY:
        # Only the vendor-recovered policy name is safe; the raw string is the
        # thing carrying the subject line.
        return not normalised
    if is_per_record(value):
        # Field type is not a safety guarantee. A misparse put
        # `<creds><USR>firstname.lastname@<customer>.org<...` into `web_domain`
        # on a live tenant — a structured taxonomy field carrying a raw log
        # fragment with a named person in it. The content test has to run on
        # every field, not only on the ones known to be free text.
        return True
    if reason == REASON_MACHINE_GENERATED:
        return False
    return field_name == "alert_name" and not include_withheld


