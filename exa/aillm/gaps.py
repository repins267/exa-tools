PROPOSE = "propose"
WITHHOLD = "withhold"

# Withhold reasons. Machine-readable on purpose: `exa aillm gaps apply` filters
# on these, and a human-readable sentence is not a filter.
REASON_HIGH_CARDINALITY = "high-cardinality-per-record"
REASON_MACHINE_GENERATED = "machine-generated"
REASON_NOT_AI = "not-ai-related"
REASON_EXCLUDED_MARTECH = "excluded-martech"
REASON_NEEDS_REVIEW = "needs-review"
REASON_ALREADY_COVERED = "covered-after-normalisation"

# Propose reasons — why this value is safe to add.
REASON_REFERENCE = "matched-reference-data"
REASON_AI_CLASSIFIED = "ai-classified"
REASON_AI_CATEGORY = "ai-category"
REASON_VENDOR_CATEGORY = "vendor-pack-category"
REASON_VENDOR_TEMPLATE = "vendor-pack-template"
REASON_AI_POLICY = "ai-policy-normalised"
REASON_AI_OVER_NOISE = "ai-signal-over-vendor-noise"
REASON_AI_PROCESS = "ai-runtime-process"

WITHHOLD_REASONS = (
    REASON_HIGH_CARDINALITY,
    REASON_MACHINE_GENERATED,
    REASON_NOT_AI,
    REASON_EXCLUDED_MARTECH,
    REASON_NEEDS_REVIEW,
    REASON_ALREADY_COVERED,
)

# A vendor noise pattern is only overridden by an AI signal that survives word
# boundaries. The shared classifier matches "LLM" anywhere, which is correct for
# ordinary alert names and wrong for base62 noise: Check Point emitted
# `dga-6WsNw.TC.c5b8LLMs` and `dga-3pQD2.TC.70e8uLlM` on a live tenant, and a
# substring match would have proposed random DGA tokens as AI alert names.
_STRONG_AI = re.compile(
    r"\bAI\b|(?-i:\bAI(?=[A-Z][a-z]))|\bLLM\b|\bGenAI\b|\bcopilot\b|\bchatbot\b|"
    r"\bgenerative\b|\bprompt\b|DSPM for AI",
    re.I,
)

# Row cap for a re-enumeration of a field the standing profile truncated. The
# standing 5,000 cap is not a sane sample: it is 5,000 arbitrary values out of
# 27,781, and on a live tenant it hid six of the eight genuine AI alert names
# behind Purview per-email noise. There is no 3,000-row API limit; 50,000 works.
_DEEP_LIMIT = 50_000

# Shapes that mean "this string was built per event, not per policy". Anything
# matching is never proposed, and its raw text never reaches disk.
_PER_RECORD = re.compile(
    r"matched for .{0,40}with subject|subject \(|[\w.+-]+@[\w-]+\.[a-z]{2,}", re.I
)
# A context-table entry is a policy/category/app name. Nothing legitimate in
# that role runs long; length alone is a reliable per-record tell.
_MAX_ENTRY_CHARS = 120

# Locally-run model runtimes and AI dev tooling. These leave no network trace
# after the initial download, so process telemetry is the only place they show
# up at all (AI Agent / AI Dev Framework Process Names, 6 rules each).
_AI_PROCESS = re.compile(
    r"ollama|lm[ _-]?studio|llama[._-]?cpp|llamafile|gpt4all|jan\.exe|msty|"
    r"anythingllm|localai|open[-_]?webui|text-generation-webui|koboldcpp|vllm|"
    r"comfyui|automatic1111|claude|cursor|copilot|continue|aider|goose|"
    r"mcp[-_]server|langchain|autogen|crewai",
    re.I,
)
# Interpreters and package managers. They RUN the frameworks above, so they are
# genuinely relevant — and they are also half of every enterprise's endpoint
# fleet. Proposing python.exe into a table six rules read would fire those rules
# on everything. Review, never auto-add.
_DEV_PROCESS = re.compile(
    r"^(python[\d.]*|pythonw|node|npm|npx|yarn|pnpm|uv|uvx|pip[\d.]*|conda|"
    r"deno|bun|ruby|perl|java)(\.exe)?$",
    re.I,
)

