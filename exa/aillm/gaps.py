@dataclass
class _Decision:
    """One raw live value, decided. Aggregated into GapValue afterwards."""

    raw: str
    value: str
    decision: str
    reason: str
    normalised: bool = False
    sources: list[str] = field(default_factory=list)
    detail: str = ""


def _classify_alert_names(
    v: TableValidation,
    profile: TenantProfile,
    packs: dict[str, VendorPack],
) -> list[_Decision]:
    """Normalise, then decide, every missing ``alert_name`` value.

    Normalisation runs FIRST and per vendor. Diffing raw values here compares
    thousands of one-shot strings and proposes adding all of them.
    """
    grouped: dict[str, list[str]] = {}
    pack_by_key: dict[str, VendorPack | None] = {}
    for raw in v.missing:
        pack = _normalising_pack(_sources(profile, v.fields, raw), packs)
        key = pack.key if pack else ""
        grouped.setdefault(key, []).append(raw)
        pack_by_key[key] = pack

    entries = set(v.entries)
    out: list[_Decision] = []
    for key, raws in grouped.items():
        pack = pack_by_key[key]
        # The distinct-value list is discarded: every decision is needed, and
        # the second return value is exactly the per-value audit trail.
        _diffable, decisions = normalise_alert_names(raws, pack)
        for raw, decision in zip(raws, decisions, strict=True):
            out.append(_decide_alert(raw, decision, pack, v, profile, entries))
    return out


def _decide_alert(
    raw: str,
    norm: Normalised,
    pack: VendorPack | None,
    v: TableValidation,
    profile: TenantProfile,
    entries: set[str],
) -> _Decision:
    value = (norm.value or raw).strip()
    sources = _sources(profile, v.fields, raw)
    templates = {t.lower() for t in pack.alert_name_templates} if pack else set()
    ai = is_ai_alert_name(value) or value.lower() in templates

    def make(decision: str, reason: str, detail: str = "") -> _Decision:
        return _Decision(
            raw=raw,
            value=value,
            decision=decision,
            reason=reason,
            normalised=norm.rewritten,
            sources=sources,
            detail=detail,
        )

    if norm.is_noise:
        # A vendor noise pattern is a strong prior, not a verdict. Palo Alto's
        # `Grayware:`/`Parked:` prefixes are domain verdicts and mostly noise —
        # but `Parked:broadstreet.ai` is a parked AI-branded domain, which is
        # precisely the shadow-AI signal this whole exercise exists to surface.
        if _STRONG_AI.search(value) and not is_per_record(value):
            return make(
                PROPOSE,
                REASON_AI_OVER_NOISE,
                f"{pack.product if pack else 'vendor'} pack treats this prefix as "
                "noise; this value carries an AI signal",
            )
        return make(
            WITHHOLD,
            REASON_MACHINE_GENERATED,
            norm.reason or "matched a vendor noise pattern",
        )

    if norm.rewritten:
        # The RAW was a per-record wrapper — one distinct string per email, with
        # the subject inside it. Only the recovered policy name may be reported,
        # and only an AI policy may be proposed. This is the branch that turned
        # 3,573 live values into 2 lines of output.
        if ai and not is_per_record(value) and value.lower() not in entries:
            return make(
                PROPOSE,
                REASON_AI_POLICY,
                f"policy name recovered from the {pack.product if pack else 'vendor'}"
                " per-record wrapper",
            )
        return make(
            WITHHOLD,
            REASON_HIGH_CARDINALITY,
            f"{pack.product if pack else 'vendor'} wraps this policy per record; "
            "the raw value is never matchable and carries message content",
        )

    if value.lower() in entries:
        return make(
            WITHHOLD,
            REASON_ALREADY_COVERED,
            "table already holds this value",
        )

    if is_per_record(raw) or is_per_record(value):
        # Per-record shape with nothing to normalise it — no pack, or a shape the
        # pack's pattern does not cover. Withholding is the only safe answer: the
        # value cannot match, and it carries content.
        return make(
            WITHHOLD,
            REASON_HIGH_CARDINALITY,
            "per-record or over-long value: never matchable as a table entry",
        )

    if not ai:
        return make(WITHHOLD, REASON_NOT_AI, "no AI/LLM signal in the value")

    if value.lower() in templates:
        return make(PROPOSE, REASON_VENDOR_TEMPLATE, "known template for this product")
    return make(PROPOSE, REASON_AI_CLASSIFIED, "AI/LLM signal in the value")


def _classify_plain(
    v: TableValidation,
    profile: TenantProfile,
    kind: str,
    ctx: dict[str, Any],
) -> list[_Decision]:
    """Decide missing values for the non-alert_name tables.

    Domains and categories reuse the discovery buckets wholesale rather than
    re-deriving them — two commands disagreeing about the same tenant is the one
    failure mode nobody can debug from the output.
    """
    entries = set(v.entries)
    out: list[_Decision] = []
    for raw in v.missing:
        value = raw.strip()
        sources = _sources(profile, v.fields, raw)
        if is_per_record(value):
            # Applies to every field, not only alert_name: a misparse can put a
            # raw log fragment into any of them, and such a value is unmatchable
            # as a table entry regardless of what it contains.
            decision, reason, detail = (
                WITHHOLD,
                REASON_HIGH_CARDINALITY,
                "per-record or over-long value: never matchable as a table entry",
            )
        else:
            decision, reason, detail = _decide_plain(value, kind, ctx)
        if decision == PROPOSE and value.lower() in entries:
            decision, reason, detail = (
                WITHHOLD,
                REASON_ALREADY_COVERED,
                "table already holds this value",
            )
        out.append(
            _Decision(
                raw=raw,
                value=value,
                decision=decision,
                reason=reason,
                sources=sources,
                detail=detail,
            )
        )
    return out


def _decide_plain(value: str, kind: str, ctx: dict[str, Any]) -> tuple[str, str, str]:
    low = value.lower()

    if kind == "domain":
        classified: dict[str, tuple[str, str]] = ctx["domains"]
        bucket, why = classified.get(low, ("", ""))
        if bucket == KNOWN:
            return PROPOSE, REASON_REFERENCE, why
        if bucket == EXCLUDED:
            return WITHHOLD, REASON_EXCLUDED_MARTECH, why
        if bucket == CANDIDATE:
            return WITHHOLD, REASON_NEEDS_REVIEW, why
        return WITHHOLD, REASON_NOT_AI, "not an AI domain by reference or pattern"

    if kind == "category":
        if low in ctx["ai_categories"]:
            return PROPOSE, REASON_AI_CATEGORY, "discovery classified this as AI"
        if low in ctx["pack_categories"]:
            return PROPOSE, REASON_VENDOR_CATEGORY, "declared by a vendor pack"
        return WITHHOLD, REASON_NOT_AI, "not an AI category"

    if kind == "app":
        if low in ctx["reference_apps"]:
            return PROPOSE, REASON_REFERENCE, "in bundled AI application data"
        if has_ai_provider_token(value):
            return PROPOSE, REASON_AI_CLASSIFIED, "names a known AI provider"
        if has_weak_ai_hint(value) or is_ai_alert_name(value):
            return WITHHOLD, REASON_NEEDS_REVIEW, "weak AI signal only"
        return WITHHOLD, REASON_NOT_AI, "no AI signal"

    if kind == "process":
        if _AI_PROCESS.search(value):
            return PROPOSE, REASON_AI_PROCESS, "known local model runtime or AI tool"
        if _DEV_PROCESS.match(value):
            return (
                WITHHOLD,
                REASON_NEEDS_REVIEW,
                "interpreter or package manager: runs AI frameworks, but also "
                "runs everything else",
            )
        return WITHHOLD, REASON_NOT_AI, "not an AI process"

    return WITHHOLD, REASON_NEEDS_REVIEW, f"no classifier for field kind {kind!r}"


def _aggregate(
    table_name: str,
    field_name: str,
    decisions: list[_Decision],
    *,
    include_withheld: bool,
) -> tuple[list[GapValue], list[GapValue]]:
    """Collapse per-value decisions into reported entries, preserving counts."""
    merged: dict[tuple[str, str, str | None], GapValue] = {}
    order: list[tuple[str, str, str | None]] = []

    for d in decisions:
        redacted = _redact(
            value=d.value,
            field_name=field_name,
            decision=d.decision,
            reason=d.reason,
            normalised=d.normalised,
            include_withheld=include_withheld,
        )
        shown = None if redacted else d.value
        key = (d.decision, d.reason, shown if shown is not None else "")
        existing = merged.get(key)
        if existing is None:
            merged[key] = GapValue(
                value=shown,
                table=table_name,
                field_name=field_name,
                decision=d.decision,
                reason=d.reason,
                raw_count=1,
                normalised=d.normalised,
                redacted=redacted,
                sources=list(d.sources),
                detail=d.detail,
            )
            order.append(key)
            continue
        existing.raw_count += 1
        existing.normalised = existing.normalised or d.normalised
        for s in d.sources:
            if s not in existing.sources:
                existing.sources.append(s)

    propose: list[GapValue] = []
    withhold: list[GapValue] = []
    for key in order:
        g = merged[key]
        g.sources.sort()
        (propose if g.decision == PROPOSE else withhold).append(g)

    propose.sort(key=lambda g: (g.value or "").lower())
    withhold.sort(key=lambda g: (-g.raw_count, g.reason, (g.value or "")))
    return propose, withhold


def build_gap_report(
    validations: list[TableValidation],
    profile: TenantProfile,
    *,
    packs: dict[str, VendorPack] | None = None,
    include_withheld_values: bool = False,
) -> GapReport:
    """Classify every missing value. Pure — no API calls, no writes.

    Args:
        validations: Output of ``validate_aillm_tables``.
        profile: The profile those validations were measured against.
        packs: Vendor packs. Loaded from the bundled data when omitted.
        include_withheld_values: Write withheld ``alert_name`` text to the
            report. Off by default: those strings are free text authored by the
            source product and carry customer content on DLP feeds.

    Returns:
        GapReport. Every examined value appears in exactly one bucket, which
        ``GapReport.balanced`` asserts.
    """
    packs = load_vendor_packs() if packs is None else packs

    domain_buckets: dict[str, tuple[str, str]] = {}
    discovery = discover_ai_domains(None, profile=profile)  # type: ignore[arg-type]
    for bucket, items in (
        (KNOWN, discovery.known),
        (CANDIDATE, discovery.candidates),
        (EXCLUDED, discovery.excluded),
    ):
        for d in items:
            domain_buckets[d.domain.lower()] = (bucket, d.reason)

    ctx: dict[str, Any] = {
        "domains": domain_buckets,
        "ai_categories": {
            c.value.lower()
            for c in discover_categories(None, profile=profile)  # type: ignore[arg-type]
        },
        "pack_categories": known_ai_categories(packs),
        "reference_apps": _reference_apps(),
    }

    report = GapReport(
        tenant=profile.tenant,
        collected_at=profile.collected_at,
        lookback_days=profile.lookback_days,
        api_calls=profile.api_calls,
        truncated_fields=sorted(
            {
                f
                for spec in TABLE_SPECS.values()
                for f in spec.fields
                if profile.truncated(f)
            }
        ),
    )

    for v in validations:
        kind = _KIND_BY_FIELD.get(v.fields[0] if v.fields else "", "")
        tg = TableGaps(
            table_name=v.table_name,
            fields=list(v.fields),
            table_id=v.table_id,
            key_attr=v.key_attr,
            status=v.status,
            records=v.records,
            consumers=list(v.consumers),
            read_by_rules=v.read_by_rules,
            truncated_sample=v.truncated_sample,
            note=v.note,
            examined=len(v.missing),
        )
        if v.missing:
            if kind == "alert_name":
                decisions = _classify_alert_names(v, profile, packs)
            else:
                decisions = _classify_plain(v, profile, kind, ctx)
            tg.propose, tg.withhold = _aggregate(
                v.table_name,
                v.fields[0] if v.fields else "",
                decisions,
                include_withheld=include_withheld_values,
            )
        report.tables.append(tg)

    return report


