def deepen_truncated_fields(
    client: ExaClient,
    profile: TenantProfile,
    *,
    limit: int = _DEEP_LIMIT,
    fields: list[str] | None = None,
) -> list[str]:
    """Re-enumerate capped fields at a higher row cap. READ-ONLY.

    Why this is not optional in practice
    ------------------------------------
    The standing profile caps each enumeration at 5,000 rows, and the cap is not
    a random sample you can reason about — it is truncated *and* non-deterministic
    between runs. On a live healthcare tenant ``alert_name`` has **27,781**
    distinct values, of which 3,573-plus are Microsoft Purview per-email strings.
    The 5,000-row sample was so dominated by that noise that six of the eight
    genuine AI alert names never appeared at all. A gap report built on it says
    "2 proposals" with total confidence and is wrong by a factor of four.

    Filtering instead of enumerating does not work here and fails silently: with
    ``groupBy`` set, this tenant IGNORES the EQL query entirely — an exact-match
    ``alert_name:"AIEnterpriseInteractionsExported"`` returned 200 unrelated
    values rather than an error. A bigger cap is the only reliable answer.

    Costs one API call per truncated field, and re-caches so the next command
    inherits the better sample. Truncation is re-recorded, never assumed cleared:
    a field still capped at the higher limit stays a lower bound.

    Returns:
        The field names that were re-enumerated.
    """
    from exa.search.events import search_events

    wanted = fields or sorted(
        {f for spec in TABLE_SPECS.values() for f in spec.fields}
    )
    deepened: list[str] = []
    for name in wanted:
        if not profile.truncated(name):
            continue
        combo = [name, "product", "vendor"]
        try:
            rows = search_events(
                client,
                "",
                fields=combo,
                lookback_days=profile.lookback_days,
                limit=limit,
                group_by=combo,
            )
            profile.api_calls += 1
        except Exception:  # noqa: BLE001 - a failed deepening keeps the old sample
            profile.api_calls += 1
            continue

        values: set[str] = set()
        attribution: dict[str, set[str]] = {}
        for row in rows:
            val = str(row.get(name) or "").strip()
            if not val or val == "None":
                continue
            values.add(val)
            vendor = str(row.get("vendor") or "").strip()
            product = str(row.get("product") or "").strip()
            if product and product != "None":
                label = (
                    f"{vendor} / {product}"
                    if vendor and vendor != "None"
                    else product
                )
                attribution.setdefault(val, set()).add(label)

        profile.fields[name] = FieldValues(
            field_name=name,
            values=sorted(values),
            truncated=len(rows) >= limit,
        )
        if attribution:
            profile.attribution[name] = {k: sorted(v) for k, v in attribution.items()}
        deepened.append(name)

    if deepened:
        save_profile(profile)
    return deepened


def analyze_gaps(
    client: ExaClient,
    *,
    profile: TenantProfile | None = None,
    lookback_days: int = 30,
    refresh: bool = False,
    include_withheld_values: bool = False,
    deep: bool = True,
) -> GapReport:
    """Measure and classify the gap between live values and each context table.

    Read-only: a profile collection (cached, usually free), one re-enumeration
    per truncated field when ``deep``, and the table reads ``validate`` already
    performs. Nothing is written to the tenant.
    """
    profile = profile or collect_tenant_profile(
        client, lookback_days=lookback_days, refresh=refresh
    )
    deepened: list[str] = []
    if deep:
        # Probe first so every field the tables are matched against exists in the
        # profile — process_name and parent_process_name are outside the standing
        # enumeration, and an unprobed field cannot be reported as truncated.
        ensure_fields(
            client,
            profile,
            sorted({f for spec in TABLE_SPECS.values() for f in spec.fields}),
        )
        deepened = deepen_truncated_fields(client, profile)

    validations = validate_aillm_tables(client, profile=profile)
    report = build_gap_report(
        validations, profile, include_withheld_values=include_withheld_values
    )
    report.deepened_fields = deepened
    return report


# How many withheld entries to LIST per reason. Counts are always complete; this
# caps the listing only. Uncapped, a tenant with 43,461 withheld web_domain
# values produced a 43 MB "reviewable" file that no reviewer would open — and
# put 43,000 lines of customer traffic on disk to say nothing a count did not.
_MAX_LISTED_PER_REASON = 200


def gap_report_to_dict(
    report: GapReport, *, max_listed_per_reason: int = _MAX_LISTED_PER_REASON
) -> dict[str, Any]:
    """Serialise for the reviewable JSON file.

    Every count is labelled a lower bound when its sample was truncated. A total
    that implies completeness is worse than no total: it retires a question that
    is still open.

    Proposals are always listed in full. Withheld entries are listed up to
    ``max_listed_per_reason`` per reason (0 = no cap), with ``listed`` and
    ``not_listed`` stated per table so the elision is visible rather than
    silent. The counts in ``withheld_by_reason`` are unaffected and complete.
    """
    return {
        "tenant": report.tenant,
        "collected_at": report.collected_at,
        "lookback_days": report.lookback_days,
        "api_calls": report.api_calls,
        "read_only": True,
        "counts_are_lower_bound": report.lower_bound,
        "truncated_fields": report.truncated_fields,
        "deepened_fields": report.deepened_fields,
        "every_value_accounted_for": report.balanced,
        "tables": [
            _table_to_dict(t, max_listed_per_reason) for t in report.tables
        ],
    }


def _table_to_dict(t: TableGaps, max_listed_per_reason: int) -> dict[str, Any]:
    listed = _listed(t, max_listed_per_reason)
    return {
        "table": t.table_name,
        "table_id": t.table_id,
        "key_attr": t.key_attr,
        "fields": t.fields,
        "consumers": t.consumers,
        "read_by_rules": t.read_by_rules,
        "status": t.status,
        "records": t.records,
        "note": t.note,
        "sample_truncated": t.truncated_sample,
        "counts_are_lower_bound": t.truncated_sample,
        "examined": t.examined,
        "proposed": t.proposed,
        "withheld_values": t.withheld_values,
        "withheld_distinct": t.withheld_distinct,
        "withheld_by_reason": t.by_reason(),
        "balanced": t.balanced,
        "propose": [_value_to_dict(g) for g in t.propose],
        "withhold": [_value_to_dict(g) for g in listed],
        "withhold_listing": {
            "max_listed_per_reason": max_listed_per_reason,
            "listed": len(listed),
            "not_listed": t.withheld_distinct - len(listed),
        },
    }


def _listed(table: TableGaps, max_per_reason: int) -> list[GapValue]:
    """Withheld entries to write out, capped per reason. Counts stay complete."""
    if max_per_reason <= 0:
        return table.withhold
    seen: dict[str, int] = {}
    out: list[GapValue] = []
    for g in table.withhold:
        n = seen.get(g.reason, 0)
        if n >= max_per_reason:
            continue
        seen[g.reason] = n + 1
        out.append(g)
    return out


def _value_to_dict(g: GapValue) -> dict[str, Any]:
    return {
        "value": g.value,
        "table": g.table,
        "field": g.field_name,
        "decision": g.decision,
        "reason": g.reason,
        "live_values": g.raw_count,
        "normalised": g.normalised,
        "redacted": g.redacted,
        "sources": g.sources,
        "detail": g.detail,
    }
