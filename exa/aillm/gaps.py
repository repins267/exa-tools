"""Gap analysis — what the tenant emits that the AI/LLM context tables lack.

``exa aillm validate`` answers ``table ∩ live``. That tells you a table is dead;
it never tells you what to put in it. This module answers the other direction,
``live − table``, and then does the part that actually takes judgement: deciding
which of those values may be added and which must not.

This command is READ-ONLY. It writes a reviewable JSON file and nothing else.

Why classification, and not just a diff
---------------------------------------
A raw diff on a live healthcare tenant returned **27,167** missing ``alert_name``
values over 30 days. Adding them would have been catastrophic and would have
looked like progress:

- **19,134** were Microsoft Purview classic DLP matches, each carrying the
  matched EMAIL SUBJECT — one distinct value per email, patient content in the
  string, and no exact-match context table can ever match them. Stripped of the
  vendor wrapper they collapse to **2** policy names.
- **7,276** were Check Point machine-generated tokens (``dga-Cai8Z.TC.893fEDbW``)
  that never recur.
- **749** were ordinary security alerts with no AI relevance at all.

**8** were genuine AI alert names. That ratio is the reason every value gets an
explicit decision and a machine-readable reason, and why nothing is ever
silently dropped: the count of examined values equals the count accounted for
in the two buckets, and the report asserts it.

What is written to disk
-----------------------
Alert names are free text authored by the source product, and on this class of
tenant they carry patient and provider names. So:

- ``propose`` values are always written — they are vetted by construction: AI
  classified, and rejected outright if they carry a per-record shape (an email
  subject, an address, or simply an implausible length for a policy name).
- ``high-cardinality-per-record`` withholds write only the NORMALISED value
  recovered by the vendor pack (the policy name), never the raw string. With no
  pack to normalise with, the value is redacted and only the count survives.
- ``machine-generated`` withholds write the value: matching a vendor's own noise
  regex proves the string was generated by the product, not typed by a person.
- every other withheld ``alert_name`` value is redacted unless the operator
  passes ``--include-withheld-values``. Counts and vendor attribution are always
  reported, which is what a reviewer needs.
- domains, categories, apps and process names are structured vendor taxonomies
  rather than free text, and are always written — they are the reviewable
  output of this command.

Counts are LOWER BOUNDS whenever the underlying profile sample was truncated.
The 5,000-value enumeration caps out on any busy tenant and is not deterministic
between runs, so "not found" never means "not present".
"""

